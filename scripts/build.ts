import { readdir, rm } from "node:fs/promises";
import { fileURLToPath } from "node:url";

export const root = fileURLToPath(new URL("../", import.meta.url));
export const sections = ["reactivity", "async", "query", "state", "components", "testing"];
const rules = `${root}solidjs-patterns/rules/`;
const files = (await readdir(rules)).sort();
if (
  files.join() !==
  sections
    .map((section) => `${section}.md`)
    .sort()
    .join()
) {
  throw new Error("Rule files and ordered sections differ");
}
const contents = await Promise.all(
  sections.map((section) => Bun.file(`${rules}${section}.md`).text()),
);
const reference = `# Solid 2 Patterns — Complete Reference\n\nGenerated from rules/ by bun run build. Do not edit this file directly.\n\n${contents.map((content) => content.replaceAll("](query.md)", "](rules/query.md)")).join("\n---\n\n")}`;
const output = `${root}solidjs-patterns/AGENTS.md`;
if (process.argv.includes("--check")) {
  if ((await Bun.file(output).text()) !== reference)
    throw new Error("AGENTS.md is out of date; run bun run build");
} else {
  await Bun.write(output, reference);
}
// Each block is a standalone module. Runtime tests import these exact snippets.
await rm(`${root}.generated`, { recursive: true, force: true });
for (let i = 0; i < sections.length; i++) {
  const blocks = [...contents[i]!.matchAll(/```(tsx?|typescript)\n([\s\S]*?)```/g)];
  for (const [index, block] of blocks.entries()) {
    await Bun.write(`${root}.generated/${sections[i]}-${index}.tsx`, block[2]!);
  }
}
console.log(`Built ${sections.length} rules and their TypeScript examples`);
